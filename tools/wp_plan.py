"""Work-package planner: cap concurrent work, rank by impact × frequency, reflow.

The planner selects, claims and closes work. It never merges: the human reviews.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.wp_schema import WorkPackage, validate_wp  # noqa: E402

MAX_IN_PROGRESS = 10
MIN_QUEUE = 20
DEFAULT_ROOT = Path(__file__).resolve().parent.parent
QUEUE = Path("docs/work-packages/queue")
BOARD = Path("docs/work-packages/BOARD.md")
STATE = Path("docs/work-packages/state.json")
CLOSED = Path("docs/work-packages/closed.toml")


def needs_refill(queued: int, threshold: int = MIN_QUEUE) -> bool:
    """The queue must be topped up before it drops below the threshold."""
    return queued < threshold


def select(wps: list[WorkPackage], in_progress: list[str],
           limit: int = MAX_IN_PROGRESS, profile: str | None = None) -> list[WorkPackage]:
    active = set(in_progress)
    budget = max(0, min(limit, MAX_IN_PROGRESS) - len(active))
    candidates = [wp for wp in wps if wp.id not in active]
    if profile:
        candidates = [wp for wp in candidates if wp.profile == profile]
    candidates.sort(key=lambda wp: (-wp.priority, wp.id))
    return candidates[:budget]


def render_board(queued: list[WorkPackage], in_progress: list[str],
                 review: list[str], done: list[str], profile: str | None = None) -> str:
    total_queued = len(queued)
    if profile:
        queued = [wp for wp in queued if wp.profile == profile]
    busy = set(in_progress) | set(review) | set(done)
    lines = ["# Work Package Board", "", "Generated by `tools/wp_plan.py --board`. Do not edit by hand.", ""]
    if needs_refill(total_queued):
        lines += [f"> Cola baja ({total_queued} < {MIN_QUEUE}): ejecutar `python3 tools/wp_generate.py --all`.", ""]
    for column, ids in (("in_progress", in_progress), ("review", review),
                        ("queued", [wp.id for wp in queued if wp.id not in busy]), ("done", done)):
        lines.append(f"## {column}")
        lines.append("")
        if ids:
            lines.extend(f"- {wid}" for wid in ids)
        else:
            lines.append("_(empty)_")
        lines.append("")
    return "\n".join(lines)


def load_queue(root: Path) -> list[WorkPackage]:
    folder = root / QUEUE
    if not folder.is_dir():
        return []
    wps = []
    for path in sorted(folder.glob("*.toml")):
        with path.open("rb") as handle:
            wps.append(validate_wp(tomllib.load(handle)))
    return wps


def load_state(root: Path) -> tuple[list[str], list[str], list[str]]:
    path = root / STATE
    if not path.is_file():
        return [], [], []
    data = json.loads(path.read_text(encoding="utf-8"))
    return list(data.get("in_progress", [])), list(data.get("review", [])), list(data.get("done", []))


def save_state(root: Path, active: list[str], review: list[str], done: list[str]) -> None:
    path = root / STATE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"in_progress": active, "review": review, "done": done},
                               indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def load_closed(root: Path) -> dict:
    path = root / CLOSED
    if not path.is_file():
        return {}
    with path.open("rb") as handle:
        return tomllib.load(handle)


def _head(root: Path) -> str:
    result = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True, check=False)
    return result.stdout.strip() if result.returncode == 0 else "unknown"


def claim(root: Path, wid: str) -> int:
    active, review, done = load_state(root)
    if wid in active or wid in review or wid in done:
        print(f"refused: {wid} is already claimed")
        return 1
    if len(active) >= MAX_IN_PROGRESS:
        print(f"refused: {MAX_IN_PROGRESS} work packages already in_progress")
        return 1
    if not (root / QUEUE / f"{wid}.toml").is_file():
        print(f"refused: {wid} is not in the queue")
        return 1
    active.append(wid)
    save_state(root, active, review, done)
    print(f"claimed {wid} ({len(active)}/{MAX_IN_PROGRESS})")
    return 0


def finish(root: Path, wid: str, metric: str) -> int:
    if not metric.strip():
        print("refused: --metric must state which metric moved")
        return 1
    active, review, done = load_state(root)
    if wid not in active:
        print(f"refused: {wid} is not in_progress")
        return 1
    active.remove(wid)
    done.append(wid)
    save_state(root, active, review, done)
    wp_file = root / QUEUE / f"{wid}.toml"
    if wp_file.is_file():
        wp_file.unlink()
    closed = load_closed(root)
    closed[wid] = {"id": wid, "metric": metric, "commit": _head(root)}
    path = root / CLOSED
    path.parent.mkdir(parents=True, exist_ok=True)
    body = ""
    for key, fields in closed.items():
        body += f"[{json.dumps(key, ensure_ascii=False)}]\n"
        body += "".join(f'{field} = {json.dumps(str(value), ensure_ascii=False)}\n'
                        for field, value in fields.items())
        body += "\n"
    path.write_text(body, encoding="utf-8")
    print(f"closed {wid}: {metric}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Plan Megi work packages")
    parser.add_argument("--board", action="store_true", help="regenerate BOARD.md")
    parser.add_argument("--select", action="store_true", help="print the next WPs")
    parser.add_argument("--claim", metavar="WP_ID", help="reserve one WP (cap: 10)")
    parser.add_argument("--done", metavar="WP_ID", help="close a claimed WP and remove it from the queue")
    parser.add_argument("--metric", default="", help="metric movement required with --done")
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument("--profile", choices=("light", "heavy"), default=None)
    parser.add_argument("--limit", type=int, default=MAX_IN_PROGRESS)
    args = parser.parse_args(argv)

    root = args.root
    wps = load_queue(root)
    active, review, done = load_state(root)
    if needs_refill(len(wps)):
        print(f"refill: needed ({len(wps)} queued < {MIN_QUEUE})")
    if args.claim and claim(root, args.claim):
        return 1
    if args.done and finish(root, args.done, args.metric):
        return 1
    if args.claim or args.done:
        # Board and selection must reflect the mutations above, not the pre-action snapshot.
        wps = load_queue(root)
        active, review, done = load_state(root)
    if args.board:
        board_path = root / BOARD
        board_path.parent.mkdir(parents=True, exist_ok=True)
        board_path.write_text(render_board(wps, active, review, done, profile=args.profile),
                              encoding="utf-8")
        print(f"wrote {BOARD}")
    if args.select:
        chosen = select(wps, active, limit=args.limit, profile=args.profile)
        for wp in chosen:
            print(f"{wp.id} [{wp.profile}] P{wp.priority} {wp.milestone} → {wp.verify_cmd}")
        print(f"selected: {len(chosen)}")
    if not any((args.board, args.select, args.claim, args.done)):
        parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
