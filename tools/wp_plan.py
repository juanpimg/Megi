"""Work-package planner: cap concurrent work and rank by impact × frequency."""

from __future__ import annotations
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.wp_schema import WorkPackage  # noqa: E402

MAX_IN_PROGRESS = 10

def select(wps: list[WorkPackage], in_progress: list[str], limit: int = MAX_IN_PROGRESS) -> list[WorkPackage]:
    active = set(in_progress)
    candidates = [wp for wp in wps if wp.id not in active]
    candidates.sort(key=lambda wp: (-wp.priority, wp.id))
    return candidates[:limit]

def render_board(queued: list[WorkPackage], in_progress: list[str], review: list[str], done: list[str]) -> str:
    lines = ["# Work Package Board", "", "Generated by `tools/wp_plan.py --board`. Do not edit by hand.", ""]
    for column, ids in (("in_progress", in_progress), ("review", review),
                        ("queued", [wp.id for wp in queued]), ("done", done)):
        lines.append(f"## {column}")
        lines.append("")
        lines.extend(f"- {wid}" for wid in ids) if ids else lines.append("_(empty)_")
        lines.append("")
    return "\n".join(lines)
