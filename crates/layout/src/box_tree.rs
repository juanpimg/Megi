//! # Layout Box Tree Representation
//!
//! Defines [`LayoutBox`], [`BoxType`], and tree structural invariants according to
//! CSS 2.2 §9 and CSS Display Module Level 3.

use css::{ComputedStyle, Float, Position};
use dom::NodeId;

use crate::geometry::{Dimensions, Rect};

/// The nature of a box in the layout tree.
#[derive(Clone, Debug, PartialEq)]
pub enum BoxType {
    /// A block container element (e.g. `div`, `p`, `body`).
    BlockNode(NodeId),
    /// An inline box (e.g. `span`, `b`, `a`).
    InlineNode(NodeId),
    /// An anonymous block box generated to wrap inline children inside a block container (§9.2.1.1).
    AnonymousBlock,
    /// An inline text fragment.
    TextNode(String),
    /// A horizontal line box generated in an IFC (CSS 2.2 §9.4.2).
    LineBox,
    /// A forced line break generated by `<br>` (CSS 2.2 §16.6.1).
    ///
    /// Formatting artifact: it has no width, no margins and never paints.
    LineBreak,
    /// An inline-block box (CSS 2.2 §9.2.1.1, §10.3.9): a block container that
    /// participates in an inline formatting context as an atomic inline-level box.
    InlineBlock(NodeId),
    /// A replaced element box (`<img>`, `<input>`, …; CSS 2.2 §9.2.2, §10.3.2).
    Replaced(NodeId),
    /// CSS table box (CSS 2.1 §17.4).
    Table(NodeId),
    /// CSS inline-table box (CSS 2.1 §17.4): a table that participates in an inline
    /// formatting context as an atomic inline-level box.
    InlineTable(NodeId),
    /// CSS table row group box (`<thead>`/`<tbody>`/`<tfoot>`, CSS 2.1 §17.2.1).
    TableRowGroup(NodeId),
    /// CSS table row box (CSS 2.1 §17.2.1).
    TableRow(NodeId),
    /// CSS table cell box (CSS 2.1 §17.2.1).
    TableCell(NodeId),
    /// CSS table caption box (CSS 2.1 §17.4).
    TableCaption(NodeId),
    /// CSS table column / column group box (kept for tree completeness; no geometry).
    TableColumn(NodeId),
    /// Anonymous table row generated by the table fix-up rules (CSS 2.1 §17.2.1).
    AnonymousTableRow,
    /// Anonymous table cell generated by the table fix-up rules (CSS 2.1 §17.2.1).
    AnonymousTableCell,
}

/// A node in the CSS layout box tree.
#[derive(Clone, Debug, PartialEq)]
pub struct LayoutBox {
    /// Geometric dimensions and box-model edge thicknesses in pixels.
    pub dimensions: Dimensions,
    /// Box classification (block, inline, anonymous, text).
    pub box_type: BoxType,
    /// Computed style associated with this box (if generated from an element).
    pub style: Option<ComputedStyle>,
    /// Number of table columns spanned by a cell (`colspan` HTML attribute,
    /// CSS 2.1 §17.5.1). `1` for every other box. `u16` keeps `LayoutBox` compact.
    pub colspan: u16,
    /// Number of table rows spanned by a cell (`rowspan` HTML attribute,
    /// CSS 2.1 §17.5.1, capped at 65534). `1` for every other box.
    pub rowspan: u16,
    /// Intrinsic (decoded) size of a replaced element in CSS pixels, when known.
    ///
    /// Filled by `layout_document_with_replaced_sizes` (or per-kind defaults for
    /// `<img>` et al.); only meaningful for [`BoxType::Replaced`].
    pub intrinsic_size: Option<(f32, f32)>,
    /// Baseline offset from the top of this box's content box, in px.
    ///
    /// For text fragments (`BoxType::TextNode`) this is the distance from
    /// `dimensions.content.y` down to the glyph baseline, so paint can place
    /// glyphs at `content.y + baseline`. Non-text boxes carry `0.0` unless a
    /// future formatting context defines a meaningful baseline.
    pub baseline: f32,
    /// Used CSS `position` (CSS 2.2 §9.3). `sticky` is preserved for paint but behaves
    /// like `relative` in this layout engine (no scrolling yet).
    pub position: Position,
    /// Used `z-index`; `auto` is normalized to `0`. Only meaningful for positioned boxes
    /// (static boxes always carry `0`).
    pub z_index: i32,
    /// Used `opacity` (1.0 = fully opaque).
    pub opacity: f32,
    /// `true` when this box establishes a new stacking context (CSS 2.2 Appendix E):
    /// the root element, a positioned box with a non-`auto` `z-index`, a `fixed` box,
    /// or a box with `opacity < 1`.
    pub establishes_stacking_context: bool,
    /// Absolute-coordinate clip rectangle inherited by this box and its descendants.
    ///
    /// `None` means "not clipped". A box that establishes clipping through
    /// `overflow: hidden|clip|scroll|auto` carries its own padding box here; descendants
    /// inherit the intersection with every ancestor clip. Paint applies it to the box
    /// content (a clipping box's own border/background follow CSS 2.2 §11 rules).
    pub clip: Option<Rect>,
    /// `true` when the box is a float (`float: left|right`, CSS 2.2 §9.5).
    pub is_float: bool,
    /// Used `float` side (`Float::None` for non-floated boxes).
    pub float_side: Float,
    /// Child boxes in layout order.
    pub children: Vec<LayoutBox>,
}

impl Drop for LayoutBox {
    /// Explicitly iterative drop: a deep layout tree (thousands of nested boxes) would
    /// otherwise overflow the stack while the compiler-generated recursive drop walks
    /// the `children` vectors.
    fn drop(&mut self) {
        if self.children.is_empty() {
            return;
        }
        let mut stack: Vec<LayoutBox> = std::mem::take(&mut self.children);
        while let Some(mut node) = stack.pop() {
            stack.append(&mut node.children);
        }
    }
}

impl LayoutBox {
    /// Creates a new layout box with zero dimensions and empty children.
    pub fn new(box_type: BoxType, style: Option<ComputedStyle>) -> Self {
        Self {
            dimensions: Dimensions::default(),
            box_type,
            style,
            colspan: 1,
            rowspan: 1,
            intrinsic_size: None,
            baseline: 0.0,
            position: Position::Static,
            z_index: 0,
            opacity: 1.0,
            establishes_stacking_context: false,
            clip: None,
            is_float: false,
            float_side: Float::None,
            children: Vec::new(),
        }
    }

    /// Returns `true` if this box is a block-level container (element block, anonymous
    /// block, or a CSS 2.1 table part that is laid out as a block-level box).
    #[inline]
    pub fn is_block(&self) -> bool {
        matches!(
            self.box_type,
            BoxType::BlockNode(_)
                | BoxType::AnonymousBlock
                | BoxType::Table(_)
                | BoxType::TableRowGroup(_)
                | BoxType::TableRow(_)
                | BoxType::TableCell(_)
                | BoxType::TableCaption(_)
                | BoxType::TableColumn(_)
                | BoxType::AnonymousTableRow
                | BoxType::AnonymousTableCell
        )
    }

    /// Returns `true` if this box participates in an inline formatting context.
    #[inline]
    pub fn is_inline(&self) -> bool {
        matches!(
            self.box_type,
            BoxType::InlineNode(_)
                | BoxType::TextNode(_)
                | BoxType::LineBreak
                | BoxType::InlineBlock(_)
                | BoxType::Replaced(_)
                | BoxType::InlineTable(_)
        )
    }

    /// Returns `true` for atomic inline-level boxes (inline-block and replaced boxes):
    /// they participate in the line as a single unbreakable unit.
    #[inline]
    pub fn is_atomic_inline(&self) -> bool {
        matches!(
            self.box_type,
            BoxType::InlineBlock(_) | BoxType::Replaced(_) | BoxType::InlineTable(_)
        )
    }

    /// Returns `true` for a CSS 2.1 table part box (including anonymous table parts).
    #[inline]
    pub fn is_table_part(&self) -> bool {
        matches!(
            self.box_type,
            BoxType::Table(_)
                | BoxType::InlineTable(_)
                | BoxType::TableRowGroup(_)
                | BoxType::TableRow(_)
                | BoxType::TableCell(_)
                | BoxType::TableCaption(_)
                | BoxType::TableColumn(_)
                | BoxType::AnonymousTableRow
                | BoxType::AnonymousTableCell
        )
    }

    /// Returns `true` if this box is an anonymous block box.
    #[inline]
    pub fn is_anonymous(&self) -> bool {
        matches!(self.box_type, BoxType::AnonymousBlock)
    }

    /// Returns `true` if this box is a line box.
    #[inline]
    pub fn is_line_box(&self) -> bool {
        matches!(self.box_type, BoxType::LineBox)
    }

    /// Returns the DOM `NodeId` if this box corresponds directly to an element.
    #[inline]
    pub fn node_id(&self) -> Option<NodeId> {
        match self.box_type {
            BoxType::BlockNode(id)
            | BoxType::InlineNode(id)
            | BoxType::InlineBlock(id)
            | BoxType::Replaced(id)
            | BoxType::Table(id)
            | BoxType::InlineTable(id)
            | BoxType::TableRowGroup(id)
            | BoxType::TableRow(id)
            | BoxType::TableCell(id)
            | BoxType::TableCaption(id)
            | BoxType::TableColumn(id) => Some(id),
            _ => None,
        }
    }
}

/// Builds the style of an anonymous box / formatting artifact from its parent.
///
/// CSS 2.2 §9.2.1.1: "The properties of anonymous boxes are inherited from the
/// enclosing non-anonymous box [...]. Non-inherited properties have their initial
/// value. For example, the font of the anonymous box is inherited from the DIV, but
/// the margins will be 0."
///
/// The inherited properties tracked by [`ComputedStyle`] are colour, the font
/// properties (`font-size`, `font-weight`, `font-style`, `font-family`), `line-height`,
/// `text-align` and `white-space` (see [`ComputedStyle::inherit_from`]). Everything
/// else (margins, paddings, borders, background, `width`/`height`, positioning,
/// `vertical-align`, `opacity`, ...) is reset to its initial value.
///
/// Note: `visibility` and `list-style-type` are not modelled by [`ComputedStyle`] yet;
/// when the CSS crate adds them they must be added to `inherit_from`, which this helper
/// delegates to.
pub fn anonymous_style_from(parent: &ComputedStyle) -> ComputedStyle {
    let mut style = ComputedStyle::initial();
    style.inherit_from(parent);
    style
}

/// Returns `true` when this box is a text box that contains only collapsible whitespace.
///
/// Such a box is insignificant between block-level siblings (CSS 2.2 §9.2.1.1 and
/// §16.6.1) and must not produce vertical gaps in pretty-printed HTML. Only the
/// collapsible ASCII whitespace characters (space, tab, newline, CR, FF) count: other
/// Unicode space characters such as NO-BREAK SPACE are visible content.
#[inline]
pub fn is_collapsible_whitespace_box(layout_box: &LayoutBox) -> bool {
    match &layout_box.box_type {
        BoxType::TextNode(text) => {
            !text.is_empty() && text.chars().all(|c| c.is_ascii_whitespace())
        }
        _ => false,
    }
}
