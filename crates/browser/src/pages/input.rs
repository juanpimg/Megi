use super::*;

/// Short deterministic code for a render error page (`DNS`, `TLS`, `HTTP`, ...).
pub fn error_code(error: &megi_webview::render::RenderError) -> &'static str {
    match error {
        megi_webview::render::RenderError::Url(_) => "URL",
        megi_webview::render::RenderError::UnsupportedScheme(_) => "SCHEME",
        megi_webview::render::RenderError::NetworkDisabled { .. } => "NETWORK_DISABLED",
        megi_webview::render::RenderError::HttpStatus { .. } => "HTTP",
        megi_webview::render::RenderError::Fetch(fetch) => match fetch {
            megi_webview::net::FetchError::Dns(_) => "DNS",
            megi_webview::net::FetchError::Tls(_)
            | megi_webview::net::FetchError::TlsUnsupported => "TLS",
            megi_webview::net::FetchError::Timeout => "TIMEOUT",
            megi_webview::net::FetchError::Connect(_) | megi_webview::net::FetchError::Io(_) => {
                "NETWORK"
            }
            megi_webview::net::FetchError::Http2(_)
            | megi_webview::net::FetchError::InvalidResponse(_) => "HTTP",
            _ => "NETWORK",
        },
        megi_webview::render::RenderError::DocumentTooLarge { .. }
        | megi_webview::render::RenderError::TooManyStylesheets { .. }
        | megi_webview::render::RenderError::StylesheetTooLarge { .. }
        | megi_webview::render::RenderError::CssBudgetExceeded { .. } => "LIMIT",
        _ => "LOAD_FAILED",
    }
}

/// Resolves a `file://` directory URL into a generated listing `data:` URL.
///
/// Returns `Ok(None)` for non-`file:` inputs, `Ok(Some(url))` when the path is a
/// directory (or cannot be read → error page is generated by the caller) and `Ok(None)`
/// for regular files.
pub fn resolve_directory(input: &str) -> Option<Result<String, (String, String)>> {
    let parsed = megi_webview::net::Url::parse(input).ok()?;
    if parsed.scheme() != megi_webview::net::url::Scheme::File {
        return None;
    }
    let path = PathBuf::from(megi_webview::net::url::percent_decode(parsed.path()));
    if !path.is_dir() {
        return None;
    }
    match read_directory(&path) {
        Ok(entries) => Some(Ok(data_url(&listing_html(input, &path, &entries)))),
        Err(error) => Some(Err(("FILE_IO".to_owned(), error.to_string()))),
    }
}

/// Resolves the input for rendering: directory listings become `data:` pages.
///
/// Errors are reported as `(code, message)` so callers can render [`error_html`].
pub fn prepare_input(input: &str) -> Result<String, (String, String)> {
    // Internal generated page: headless renders its empty deterministic state; the window
    // fills it from the live per-tab history before requesting the render.
    if crate::history::is_history_url(input) {
        return Ok(data_url(&crate::history::history_page_html(&[])));
    }
    if is_about_page_url(input) {
        return Ok(data_url(&about_page_html(input)));
    }
    if is_settings_url(input) {
        return Ok(data_url(&settings_page_html()));
    }
    match resolve_directory(input) {
        Some(Ok(url)) => Ok(url),
        Some(Err(error)) => Err(error),
        None => Ok(input.to_owned()),
    }
}
