    pub(crate) fn all_chunks(bytes: &[u8], size: usize) -> Vec<Vec<u8>> {
        bytes
            .chunks(size.max(1))
            .map(|chunk| chunk.to_vec())
            .collect()
    }

    pub(crate) fn stream_through(
        inflater: &mut StreamingInflater,
        chunks: &[Vec<u8>],
    ) -> Result<Vec<u8>, InflateError> {
        let mut output = Vec::new();
        for chunk in chunks {
            inflater.feed(chunk, &mut output)?;
        }
        inflater.finish()?;
        Ok(output)
    }

