//! WebP lossless (VP8L) subset decoder — `std` only, no `unsafe`.
//!
//! ## Supported subset (verified against PIL/libwebp-generated fixtures)
//!
//! - RIFF/WEBP container: `VP8L` chunk (lossless); `VP8 ` (lossy) is detected and rejected
//!   with a clear [`ImageError::UnsupportedFeature`];
//! - VP8L header (signature, 14-bit width/height, alpha-used flag, version 0);
//! - **simple Huffman codes** (one or two symbols) for the five meta codes
//!   (green/literal, red, blue, alpha, distance);
//! - literal-only pixel data, ARGB -> straight RGBA8 (alpha preserved);
//! - defensive limits: dimensions/pixels from [`PngLimits`] are checked before allocating.
//!
//! ## Not supported yet (documented subset; typed errors, never panics)
//!
//! - **VP8 lossy** (`VP8 ` chunk);
//! - VP8L transforms (predictor, colour, subtract-green, colour indexing) — libwebp
//!   enables them automatically for most real images, so photos currently fall back to the
//!   renderer's placeholder with a warning;
//! - complex Huffman codes, meta Huffman images, colour cache and LZ77 backward
//!   references (the decoder rejects them explicitly instead of mis-decoding).
//!
//! The fixtures in `tests/fixtures/webp/` are tiny valid VP8L files with a simple Huffman
//! payload (generated by `tests/fixtures/generate_webp.py` and verified with PIL) so the
//! supported path is byte-exact against an independent decoder.

use crate::RgbaImage;
use crate::error::ImageError;
use crate::png::PngLimits;

/// VP8L chunk signature byte.
const VP8L_SIGNATURE: u8 = 0x2f;
/// `RIFF` header + `WEBP` form type.
const RIFF_HEADER_LEN: usize = 12;

/// LSB-first bit reader for the VP8L bitstream (RFC-like spec §4).
struct BitReader<'a> {
    data: &'a [u8],
    bit: usize,
}

impl<'a> BitReader<'a> {
    fn new(data: &'a [u8]) -> Self {
        Self { data, bit: 0 }
    }

    fn read_bit(&mut self) -> Result<u32, ImageError> {
        let byte = *self.data.get(self.bit / 8).ok_or(ImageError::Truncated {
            context: "WebP VP8L bitstream",
        })?;
        let value = u32::from((byte >> (self.bit % 8)) & 1);
        self.bit += 1;
        Ok(value)
    }

    fn read_bits(&mut self, count: u32) -> Result<u32, ImageError> {
        if count > 24 {
            return Err(ImageError::InvalidData {
                reason: "VP8L bit read larger than 24 bits",
            });
        }
        let mut value = 0u32;
        for shift in 0..count {
            value |= self.read_bit()? << shift;
        }
        Ok(value)
    }
}

/// One decoded simple Huffman code: no bits (single symbol) or one bit (two symbols).
struct SimpleCode {
    first: u16,
    second: Option<u16>,
}

impl SimpleCode {
    fn decode(&self, reader: &mut BitReader<'_>) -> Result<u16, ImageError> {
        match self.second {
            None => Ok(self.first),
            Some(second) => {
                let low = self.first.min(second);
                let high = self.first.max(second);
                Ok(if reader.read_bit()? == 0 { low } else { high })
            }
        }
    }
}

/// Reads one VP8L "simple Huffman code" for `alphabet_size` symbols.
fn read_simple_code(
    reader: &mut BitReader<'_>,
    alphabet_size: u16,
) -> Result<SimpleCode, ImageError> {
    if reader.read_bit()? == 0 {
        return Err(ImageError::UnsupportedFeature {
            feature: "WebP VP8L complex Huffman codes (only simple codes are decoded in this subset)",
        });
    }
    let symbol_count = reader.read_bit()? + 1;
    let first_length_code = reader.read_bit()?;
    let first_symbol = reader.read_bits(if first_length_code == 0 { 1 } else { 8 })? as u16;
    if first_symbol >= alphabet_size {
        return Err(ImageError::InvalidData {
            reason: "VP8L Huffman symbol outside the alphabet",
        });
    }
    if symbol_count == 2 {
        let second_symbol = reader.read_bits(8)? as u16;
        if second_symbol >= alphabet_size {
            return Err(ImageError::InvalidData {
                reason: "VP8L Huffman symbol outside the alphabet",
            });
        }
        if second_symbol == first_symbol {
            return Err(ImageError::InvalidData {
                reason: "VP8L simple Huffman code repeats a symbol",
            });
        }
        Ok(SimpleCode {
            first: first_symbol,
            second: Some(second_symbol),
        })
    } else {
        Ok(SimpleCode {
            first: first_symbol,
            second: None,
        })
    }
}

/// Locates the `VP8L` chunk inside a RIFF/WEBP container and returns its payload.
fn find_vp8l_chunk(bytes: &[u8]) -> Result<&[u8], ImageError> {
    if bytes.len() < RIFF_HEADER_LEN || !bytes.starts_with(b"RIFF") || &bytes[8..12] != b"WEBP" {
        return Err(ImageError::InvalidSignature);
    }
    let mut offset = RIFF_HEADER_LEN;
    while offset + 8 <= bytes.len() {
        let id = &bytes[offset..offset + 4];
        let length = u32::from_le_bytes([
            bytes[offset + 4],
            bytes[offset + 5],
            bytes[offset + 6],
            bytes[offset + 7],
        ]) as usize;
        let payload_start = offset + 8;
        let payload_end = payload_start
            .checked_add(length)
            .ok_or(ImageError::Truncated {
                context: "WebP RIFF chunk",
            })?;
        if payload_end > bytes.len() {
            return Err(ImageError::Truncated {
                context: "WebP RIFF chunk payload",
            });
        }
        if id == b"VP8L" {
            return Ok(&bytes[payload_start..payload_end]);
        }
        if id == b"VP8 " {
            return Err(ImageError::UnsupportedFeature {
                feature: "WebP VP8 lossy decoding is not supported (only VP8L lossless)",
            });
        }
        // Chunks are padded to an even size.
        offset = payload_end + (length & 1);
    }
    Err(ImageError::InvalidData {
        reason: "WebP container has no VP8L or VP8 chunk",
    })
}

/// Decodes a VP8L (lossless) WebP image into RGBA8.
pub(crate) fn decode_webp(bytes: &[u8], limits: &PngLimits) -> Result<RgbaImage, ImageError> {
    let payload = find_vp8l_chunk(bytes)?;
    let Some((&signature, bitstream)) = payload.split_first() else {
        return Err(ImageError::Truncated {
            context: "WebP VP8L payload",
        });
    };
    if signature != VP8L_SIGNATURE {
        return Err(ImageError::InvalidData {
            reason: "invalid VP8L signature",
        });
    }
    let mut reader = BitReader::new(bitstream);
    let width = reader.read_bits(14)? + 1;
    let height = reader.read_bits(14)? + 1;
    let _alpha_used = reader.read_bit()?;
    let version = reader.read_bits(3)?;
    if version != 0 {
        return Err(ImageError::UnsupportedFeature {
            feature: "unsupported WebP VP8L version",
        });
    }
    if width > limits.max_dimension || height > limits.max_dimension {
        return Err(ImageError::LimitExceeded {
            what: "WebP dimension",
            limit: u64::from(limits.max_dimension),
            actual: u64::from(width.max(height)),
        });
    }
    let pixels = u64::from(width) * u64::from(height);
    if pixels > limits.max_pixels {
        return Err(ImageError::LimitExceeded {
            what: "WebP pixel count",
            limit: limits.max_pixels,
            actual: pixels,
        });
    }
    // Transforms: the current subset rejects them explicitly (libwebp enables predictor /
    // colour / subtract-green / indexing transforms automatically for most real images).
    if reader.read_bit()? == 1 {
        let transform = reader.read_bits(2)?;
        return Err(ImageError::UnsupportedFeature {
            feature: match transform {
                0 => "WebP VP8L predictor transform is not supported yet (documented subset)",
                1 => "WebP VP8L colour transform is not supported yet (documented subset)",
                2 => "WebP VP8L subtract-green transform is not supported yet (documented subset)",
                _ => "WebP VP8L colour-indexing transform is not supported yet (documented subset)",
            },
        });
    }
    if reader.read_bit()? == 1 {
        return Err(ImageError::UnsupportedFeature {
            feature: "WebP VP8L colour cache is not supported yet (documented subset)",
        });
    }
    if reader.read_bit()? == 1 {
        return Err(ImageError::UnsupportedFeature {
            feature: "WebP VP8L meta Huffman codes are not supported yet (documented subset)",
        });
    }
    // Five Huffman codes: green/literal (256 + 24 length codes), red, blue, alpha, distance.
    let green = read_simple_code(&mut reader, 256 + 24)?;
    let red = read_simple_code(&mut reader, 256)?;
    let blue = read_simple_code(&mut reader, 256)?;
    let alpha = read_simple_code(&mut reader, 256)?;
    let _distance = read_simple_code(&mut reader, 40)?;
    let capacity = usize::try_from(pixels * 4).map_err(|_| ImageError::LimitExceeded {
        what: "WebP RGBA buffer",
        limit: limits.max_pixels,
        actual: pixels,
    })?;
    let mut data = Vec::with_capacity(capacity);
    let mut pixel_count = 0u64;
    while pixel_count < pixels {
        let green_symbol = green.decode(&mut reader)?;
        if green_symbol >= 256 {
            return Err(ImageError::UnsupportedFeature {
                feature: "WebP VP8L LZ77 length codes are not supported yet (documented subset)",
            });
        }
        let red_value = red.decode(&mut reader)?;
        let blue_value = blue.decode(&mut reader)?;
        let alpha_value = alpha.decode(&mut reader)?;
        data.push(red_value as u8);
        data.push(green_symbol as u8);
        data.push(blue_value as u8);
        data.push(alpha_value as u8);
        pixel_count += 1;
    }
    RgbaImage::new(width, height, data)
}
